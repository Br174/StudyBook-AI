import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import 'fake-indexeddb/auto';
import {saveLibraryBook,getLibraryBook,listLibraryBooks} from '../src/lib/library.js';

const [screens,css,app,workflow] = await Promise.all([
 'src/components/AppScreens.jsx','src/appShellV16.css','src/AppV15.jsx','.github/workflows/android-apk.yml',
].map(path=>readFile(path,'utf8')));

const cover=screens.slice(screens.indexOf('function BookCover('),screens.indexOf('export function BottomNav('));
const library=screens.slice(screens.indexOf('export function LibraryScreen('),screens.indexOf('function ScannedBookPhoto('));
const lab18=css.slice(css.indexOf('/* LAB18 — LIBRERIA APPROVATA'));
assert.ok(lab18.length>2000,'scoped library styles provided');
assert.match(lab18,/\.sb-library-screen \.sb-library-grid\s*\{[\s\S]*?grid-template-columns:repeat\(3,minmax\(0,1fr\)\)/,'three books per row explicitly override narrow-screen fallback');
assert.ok(lab18.includes('.sb-library-compact-cover .sb-cover-title'),'fallback title styles isolated to library');
assert.ok(lab18.includes('text-align:center') && lab18.includes('-webkit-line-clamp:3'),'small balanced centered titles, truncated');
assert.ok(lab18.includes('aspect-ratio:3/4') && lab18.includes('max-width:126px'),'small proportional volumes');
assert.ok(lab18.includes('.sb-library-categories button') && lab18.includes('min-height:62px'),'first filter row larger');
assert.ok(lab18.includes('.sb-library-modes button') && lab18.includes('min-height:55px'),'second filter row larger');
assert.ok(lab18.includes('.sb-filter-strip button') && lab18.includes('min-height:51px'),'subject filter row larger');
assert.ok(lab18.includes('env(safe-area-inset-bottom'),'three-column scroll finishes above fixed navigation');
assert.ok(cover.includes('sb-library-compact-cover') && cover.includes('sb-cover-title') && cover.includes('sb-cover-brand'),'elegant accessible fallback volume in existing BookCover');
assert.ok(cover.includes('item.coverUrl || item.metadata?.coverUrl'),'real existing book covers preferred');
assert.ok(cover.includes('sb-library-cover-image') && cover.includes('alt={'), 'real book cover accessible');
assert.ok(cover.includes('onPointerDown={startHold}') && cover.includes('onClick={openBook}'), 'opening and long-press deletion remain available');
assert.ok(cover.includes('onRenameRequest(item)') && cover.includes('sb-library-rename'), 'rename stays available');
for(const tab of ['Scannerizzati','Modificati','Originali','Tutti','Materie','Raccolte','Preferiti']) assert.ok(library.includes(tab),'existing library tab '+tab);
assert.ok(library.includes('ScannerArchive {...scannerProps}'),'scanner archive preserved');
assert.ok(library.includes('onOpen={onOpenBook}'),'book opening route unchanged');
assert.ok(app.includes('onDeleteBook={removeLibraryItem}') && app.includes('onRenameBook={renameLibraryBook}'),'library database handlers preserved');
assert.ok(workflow.includes('StudyBook-AI-LAB-18-AGGIORNAMENTO') && workflow.includes('STUDYBOOK_SIGNING_MODE=update'),'original Android signing identity selected');

// The visual improvement does not migrate, rewrite, reimport or duplicate data.
await saveLibraryBook({id:'lab18-regression',fileName:'Esempio senza copertina.pdf',profileId:'default'});
const books=await listLibraryBooks({profileId:'default'});
assert.equal(books.length,1,'no duplicate book generated by library layout');
assert.equal((await getLibraryBook('lab18-regression')).fileName,'Esempio senza copertina.pdf','original record unchanged');
console.log('LAB18 Library 3 columns, compact placeholders, large tabs, preserved data/rename/delete: PASS');
