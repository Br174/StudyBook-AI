import 'fake-indexeddb/auto';
import assert from 'node:assert/strict';
import {makeGeminiPause,readGeminiPause,registerGeminiPause,clearGeminiPause,quotaDisplayV36} from '../src/lib/geminiQuotaControllerV36.js';
const now=Date.parse('2026-11-06T12:00:00.000Z');
await clearGeminiPause();
const first=await registerGeminiPause({kind:'requests-minute',automatic:true,retryAfterSeconds:75,estimated:false},{now});
assert.equal(first.persistent,true);
assert.equal(first.attempts,1);assert.equal(Date.parse(first.retryAt),now+75000);
assert.match(quotaDisplayV36(first),/richieste al minuto/);
const active=await readGeminiPause({now:now+1000});assert.equal(active.kind,'requests-minute');
const elapsed=await readGeminiPause({now:now+76000});assert.equal(elapsed,null);
const again=await registerGeminiPause({kind:'unknown',automatic:true,estimated:true},{now:now+90000});
const again2=await registerGeminiPause({kind:'unknown',automatic:true,estimated:true},{now:now+92000});
assert.ok(Date.parse(again2.retryAt)-now-92000>Date.parse(again.retryAt)-now-90000);
await clearGeminiPause();
const manual=await registerGeminiPause({kind:'no-free-allocation',automatic:false},{now});
assert.equal(manual.automatic,false);assert.equal(manual.retryAt,null);
assert.equal((await readGeminiPause({now:now+48*3600000})).kind,'no-free-allocation');
await clearGeminiPause();
assert.equal(await readGeminiPause(),null);
console.log('LAB36 free quota persistent cooldown, expiry, manual no-paid and exponential fallback OK');
